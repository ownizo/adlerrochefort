MARK = "<!-- ipmi-april -->"


def run():
    for lang, c in CFG.items():
        f = PUBLIC / c["file"] / "index.html"
        s = f.read_text(encoding="utf-8")
        if MARK in s:
            print("already done", lang)
            continue
        for a, b in c["repl"]:
            assert a in s, (lang, a)
            s = s.replace(a, b)
        # comparison table: one more column
        i = s.index('<table class="ar-table">')
        j = s.index("</table>", i)
        t = s[i:j].replace("<th>Cigna Global</th></tr>", "<th>Cigna Global</th><th>APRIL International</th></tr>", 1)

        def row(m):
            return m.group(0)[:-5] + f"<td>{c['cells'][m.group(1)]}</td></tr>"
        t, n = re.subn(r"<tr><td>([^<]*)</td><td>[^<]*</td><td>[^<]*</td></tr>", row, t)
        assert n == len(c["cells"]), (lang, n)
        s = s[:i] + t + s[j:]
        # insurer guides line and card
        hub = "/" + c["file"] + "/"
        s = re.sub(r'(<!-- ipmi-insurer-links --><p class="lp-form-micro">.*?)(</p>)',
                   lambda m: m.group(1) + f' · <a href="{hub}april-international/">{c["guide"]}</a>' + m.group(2), s, count=1, flags=re.S)
        k = s.index(f"<h3>{c['after_card']}</h3>")
        k = s.index("</div>", k) + len("</div>")
        h, p = c["card"]
        s = s[:k] + f'\n      <div class="lp-card">{MARK}<h3>{h}</h3><p>{p}</p></div>' + s[k:]
        # structured data: brand and knowsAbout
        s = s.replace('          "name": "Cigna Global"\n        }\n      ],',
                      '          "name": "Cigna Global"\n        },\n        {\n          "@type": "Brand",\n          "name": "APRIL International"\n        }\n      ],', 1)
        s = s.replace('        "Allianz Care",\n        "Cigna Global"\n      ]', '        "Allianz Care",\n        "Cigna Global",\n        "APRIL International"\n      ]', 1)
        for b in re.findall(r'<script type="application/ld\+json">(.*?)</script>', s, re.S):
            json.loads(b)
        f.write_text(s, encoding="utf-8")
        print("updated", lang)


if __name__ == "__main__":
    run()
