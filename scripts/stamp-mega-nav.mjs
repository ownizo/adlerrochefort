#!/usr/bin/env node
/**
 * Stamp each language's homepage navigation onto every other page in that
 * language, so the visitor always has Portugal / Spain / Private Clients,
 * a language selector and a quote CTA — the same header, wherever they are.
 *
 * Homepages remain the source of truth. Hash links (#contact, #blog) are
 * rewritten to the homepage so they do not resolve against the current URL.
 *
 * After this pass, run scripts/lang-switcher.mjs so the stamped selector
 * points at this page's counterparts rather than the homepage's.
 *
 * PT product pages under /seguros/ and /private-clients/ already carry the
 * Portuguese homepage nav; they are included so they cannot drift. Thank-you
 * and utility pages are skipped.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';
import { extractSiteNav, extractMobileNav } from './lib/mega-nav.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC = join(ROOT, 'public');
const DRY = process.argv.includes('--dry-run');

const HOMES = {
  pt: { file: 'index.html', root: '/' },
  en: { file: 'en/index.html', root: '/en/' },
  de: { file: 'de/index.html', root: '/de/' },
  nl: { file: 'nl/index.html', root: '/nl/' },
  fr: { file: 'fr/index.html', root: '/fr/' },
  // se/dk/pl/zh/il are generated by scripts/lib/market-cluster.mjs with the
  // same mega-nav already. Stamping the homepage onto them would rewrite the
  // in-page quote CTA (#offert) into a homepage hash.
};

const SKIP = [
  /email-signature\.html$/,
  /\/descarregar\//,
  /\/obrigado\//,
  /\/thank-you\//,
  /\/bedankt\//,
  /\/alterarmediador\//,
];

const SCRIPT_TAG = '<script defer src="/js/ar-nav.js"></script>';
const CSS_LINK = '<link rel="stylesheet" href="/css/ar-chrome.css">';

function between(html, start, end) {
  const s = html.indexOf(start);
  if (s === -1) return null;
  const e = html.indexOf(end, s);
  if (e === -1) return null;
  return html.slice(s, e + end.length);
}

function extractNav(html) {
  const nav = html.match(/<nav class="site-nav[^"]*"[^>]*>[\s\S]*?<\/nav>/);
  return nav ? nav[0] : null;
}

function extractMobile(html) {
  return between(html, '<!-- MOBILE NAV -->', '\n</div>') ||
    between(html, '<div class="mobile-nav" id="mobileNav">', '\n</div>');
}

function absolutise(chunk, root) {
  return chunk
    .replace(/href="#([a-z0-9-]+)"/gi, `href="${root}#$1"`)
    .replace(/href="#"/g, `href="${root}"`);
}

function langOf(rel) {
  const first = rel.split('/')[0];
  if (HOMES[first]) return first;
  if (rel.startsWith('blog/') || rel.startsWith('seguros/') || rel === 'index.html') return 'pt';
  if (rel.startsWith('private-clients')) return 'pt';
  if (rel.startsWith('mediador') || rel.startsWith('contacto')) return 'pt';
  // other PT commercial roots
  if (!rel.includes('/')) return 'pt';
  const top = rel.split('/')[0];
  if (['css', 'js', 'images', 'en', 'de', 'nl', 'fr', 'se', 'dk', 'pl', 'zh', 'il'].includes(top)) {
    return HOMES[top] ? top : null;
  }
  return 'pt';
}

function replaceFirst(html, pattern, replacement) {
  const m = html.match(pattern);
  if (!m) return { html, hit: false };
  return { html: html.replace(m[0], replacement), hit: true };
}

function ensureHeadLink(html, tag) {
  if (html.includes(tag)) return html;
  if (!html.includes('</head>')) return html;
  return html.replace('</head>', `${tag}\n</head>`);
}

function ensureScript(html) {
  if (html.includes('/js/ar-nav.js')) return html;
  if (html.includes('</body>')) {
    return html.replace('</body>', `${SCRIPT_TAG}\n</body>`);
  }
  return html;
}

function replaceMobile(html, mobile) {
  if (!mobile) return html;
  const existing = extractMobileNav(html);
  if (existing) return html.replace(existing, mobile);
  const headerClose = html.indexOf('</header>');
  if (headerClose !== -1) {
    return html.slice(0, headerClose + 9) + '\n\n' + mobile + html.slice(headerClose + 9);
  }
  const idx = html.indexOf('</nav>');
  if (idx !== -1) {
    return html.slice(0, idx + 6) + '\n\n' + mobile + html.slice(idx + 6);
  }
  return html;
}

const sources = {};
for (const [lang, meta] of Object.entries(HOMES)) {
  const html = await readFile(join(PUBLIC, meta.file), 'utf8');
  const nav = extractSiteNav(html);
  const mobile = extractMobileNav(html);
  if (!nav || !nav.includes('nav-links-left')) {
    console.error(`no mega-nav on ${meta.file} — skipping ${lang}`);
    continue;
  }
  sources[lang] = {
    nav: absolutise(nav, meta.root),
    mobile: mobile ? absolutise(mobile, meta.root) : null,
    homeRel: meta.file,
  };
}

const files = execSync('find public -name "*.html"', { cwd: ROOT })
  .toString()
  .trim()
  .split('\n')
  .filter(Boolean);

let written = 0;
let skipped = 0;
const byLang = {};

for (const relFind of files) {
  const rel = relFind.replace(/^public\//, '');
  if (SKIP.some((re) => re.test(relFind))) {
    skipped++;
    continue;
  }
  const lang = langOf(rel);
  const src = sources[lang];
  if (!src) {
    skipped++;
    continue;
  }
  if (rel === src.homeRel) continue; // homepage is the source

  const file = join(PUBLIC, rel);
  let html = await readFile(file, 'utf8');
  const before = html;

  const replaced = replaceFirst(
    html,
    /<nav class="site-nav[^"]*"[^>]*>[\s\S]*?<\/nav>/,
    src.nav
  );
  if (!replaced.hit) {
    skipped++;
    continue;
  }
  html = replaced.html;
  html = replaceMobile(html, src.mobile);
  html = ensureHeadLink(html, CSS_LINK);
  html = ensureScript(html);

  if (html === before) continue;
  if (!DRY) await writeFile(file, html);
  written++;
  byLang[lang] = (byLang[lang] || 0) + 1;
}

console.log(JSON.stringify({ written, skipped, byLang, dryRun: DRY }, null, 2));
