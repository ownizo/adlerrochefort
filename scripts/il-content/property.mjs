/**
 * /il/buying-property-portugal/ — buying a property, read as an insurance
 * timeline rather than as a conveyancing guide.
 *
 * Brief §11 asks for three stages plus a mistakes section. The stages are the
 * useful frame because insurance in a Portuguese purchase is not one decision
 * taken once: the lender wants a policy in place before the deed, the deed
 * itself is the moment risk transfers, and the months after completion are
 * when the things that invalidate a claim quietly happen — renovations,
 * letting, long vacancies.
 *
 * The mistakes section is the page's centre of gravity and every item on it is
 * a real pattern rather than a rhetorical one:
 *
 *   * purchase price as sum insured — the single most expensive error, in both
 *     directions. Algarve land can be most of the price, so insuring the price
 *     over-insures the building and pays for nothing; a Lisbon flat bought in
 *     2015 can now be under-insured at its own purchase price.
 *   * assuming seismic cover, which §6 already forbids presenting as automatic
 *     and which an Israeli reader is especially likely to assume, because in
 *     Israel earthquake cover is the norm inside a home policy.
 *   * under-declaring contents, which triggers `regra proporcional` — the
 *     familiar Hebrew ביטוח חסר.
 *   * undeclared letting, including Alojamento Local, which is the most common
 *     way an otherwise valid policy stops responding.
 *   * not updating after works, and vacancy conditions.
 *
 * On the mortgage: Portuguese lenders in practice require buildings cover and
 * usually life cover, and will offer their own. The honest, useful line is
 * that the borrower may generally place the cover elsewhere provided it meets
 * the lender's requirements — stated with the qualifier, because the terms are
 * the bank's and the repository cannot promise a given bank's behaviour.
 */
